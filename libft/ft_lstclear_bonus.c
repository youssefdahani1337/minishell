#include "libft.h"

void	ft_lstclear(t_list **lst)
{
	t_list	*t;

	if (!lst || !lst[0])
		return ;
	while (lst[0])
	{
		t = lst[0]->next;
		free(lst[0]);
		lst[0] = t;
	}
	lst[0] = NULL;
}
